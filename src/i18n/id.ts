export function translateIndonesian(text: string): string {
  if (indonesian[text]) return indonesian[text]
  const patterns: [RegExp, string][] = [
    [/^Pause (.+)$/, 'Jeda $1'],
    [/^Resume (.+)$/, 'Lanjutkan $1'],
    [/^Stop (.+)$/, 'Hentikan $1'],
    [/^Play (.+)$/, 'Putar $1'],
    [/^(\d+) expressions$/, '$1 ekspresi'],
  ]
  for (const [pattern, replacement] of patterns)
    if (pattern.test(text)) return text.replace(pattern, replacement)
  return text
}
